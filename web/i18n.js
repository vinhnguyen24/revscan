function t(lang, key, vars = {}) {
  const L = normalizeLang(lang);
  const dict = MESSAGES[L] || MESSAGES.vi;
  // Non-EN/VI languages gracefully fall back to EN first for technical copy,
  // then VI, so UI stays readable for international users.
  let text = dict[key];
  if (text === undefined) {
    text = (L !== 'vi' ? MESSAGES.en[key] : undefined) ?? MESSAGES.vi[key] ?? key;
  }
  if (typeof text !== 'string') return text;
  for (const [k, v] of Object.entries(vars)) {
    text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}

function planFeatures(lang, planId, fallback) {
  const L = normalizeLang(lang);
  const byLang = MESSAGES[L]?.planFeatures?.[planId];
  if (Array.isArray(byLang)) return byLang;
  if (L !== 'vi' && Array.isArray(MESSAGES.en.planFeatures?.[planId])) {
    return MESSAGES.en.planFeatures[planId];
  }
  return fallback || [];
}

