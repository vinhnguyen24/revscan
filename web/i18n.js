const LANGUAGES = [
  { code: 'vi', short: 'VI', label: 'Tiếng Việt' },
  { code: 'en', short: 'EN', label: 'English' },
  { code: 'ja', short: 'JA', label: '日本語' },
  { code: 'ko', short: 'KO', label: '한국어' },
  { code: 'zh', short: 'ZH', label: '中文' },
  { code: 'de', short: 'DE', label: 'Deutsch' },
  { code: 'fr', short: 'FR', label: 'Français' },
  { code: 'es', short: 'ES', label: 'Español' },
  { code: 'pt', short: 'PT', label: 'Português' },
  { code: 'ru', short: 'RU', label: 'Русский' },
  { code: 'pl', short: 'PL', label: 'Polski' },
  { code: 'id', short: 'ID', label: 'Bahasa Indonesia' },
];

const SUPPORTED = new Set(LANGUAGES.map((l) => l.code));
const DEFAULT_LANG = 'vi';

function normalizeLang(value) {
  const raw = String(value || '').trim().toLowerCase().replace('_', '-');
  const base = raw.split('-')[0];
  return SUPPORTED.has(base) ? base : DEFAULT_LANG;
}

function langFromRequest(url, cookieHeader, parseCookies) {
  const queryLang = url && url.searchParams ? url.searchParams.get('lang') : null;
  if (queryLang) {
    const norm = String(queryLang).trim().toLowerCase().split(/[-_]/)[0];
    if (SUPPORTED.has(norm)) return norm;
  }
  if (parseCookies && cookieHeader) {
    const cookies = parseCookies(cookieHeader);
    if (cookies.tk_lang) {
      const norm = String(cookies.tk_lang).trim().toLowerCase().split(/[-_]/)[0];
      if (SUPPORTED.has(norm)) return norm;
    }
  }
  return DEFAULT_LANG;
}

